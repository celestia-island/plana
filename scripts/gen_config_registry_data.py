#!/usr/bin/env python3
"""Regenerate `packages/config/data/` from a provider-registry checkout.

`plana_config` embeds the provider entrypoint TOMLs at build time (the
provider catalog its config layer resolves) plus a COMPACT model-score table
extracted from the registry's model cards — the 1109 full model TOMLs are
~4.5 MiB, while the scores they contribute are a few dozen KiB, and the
config layer only ever reads `[model.score].value`.

Usage:
    python3 scripts/gen_config_registry_data.py [--registry-dir DIR]

Default registry dir = `target/provider-registry` (what `just sync
provider-registry` writes). Run `just regen-config-registry` to sync +
regenerate in one step. The generated data is CHECKED IN so the crate
builds (and publishes) without the network; a deliberate registry refresh
must re-run this script and commit the diff.
"""

from __future__ import annotations

import argparse
import pathlib
import shutil
import sys

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - py<3.11
    sys.exit("python3.11+ required (tomllib)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry-dir", default="target/provider-registry")
    ap.add_argument("--out", default="packages/config/data")
    args = ap.parse_args()

    reg = pathlib.Path(args.registry_dir)
    out = pathlib.Path(args.out)
    if not (reg / "entrypoint").is_dir():
        sys.exit(f"no entrypoint dir under {reg} — run `just sync provider-registry` first")

    # 1) entrypoint TOMLs: copied verbatim (the config layer parses them).
    dst_ep = out / "provider-registry" / "entrypoint"
    if dst_ep.exists():
        shutil.rmtree(dst_ep)
    shutil.copytree(reg / "entrypoint", dst_ep)

    # 2) model scores: one compact table, keyed by provider + normalized
    #    model-file stem exactly as the config lookup normalizes them.
    scores: dict[str, dict[str, float]] = {}
    checked = 0
    with_score = 0
    for provider_dir in sorted((reg / "models").iterdir()) if (reg / "models").is_dir() else []:
        if not provider_dir.is_dir():
            continue
        for card in sorted(provider_dir.glob("*.toml")):
            checked += 1
            try:
                doc = tomllib.loads(card.read_text(encoding="utf-8"))
            except Exception:
                continue
            value = doc.get("model", {}).get("score", {}).get("value")
            if isinstance(value, float) or isinstance(value, int):
                scores.setdefault(provider_dir.name, {})[card.stem] = float(value)
                with_score += 1
    lines = [
        "# GENERATED by scripts/gen_config_registry_data.py — do not edit by hand.",
        "# Source: provider-registry model cards ([model.score].value).",
        "# Refresh: `just regen-config-registry` (syncs + regenerates + you commit).",
        "",
        "[scores]",
    ]
    for provider in sorted(scores):
        lines.append(f"[scores.{provider}]")
        for stem in sorted(scores[provider]):
            lines.append(f'"{stem}" = {scores[provider][stem]!r}')
        lines.append("")
    (out / "model-scores.toml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(
        f"entrypoint: {len(list(dst_ep.rglob('*.toml')))} tomls; "
        f"model cards: {checked}, with score: {with_score}; "
        f"scores out: {out / 'model-scores.toml'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
